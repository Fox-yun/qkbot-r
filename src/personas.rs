pub fn templates() -> BTreeMap<String, String> {
    TEMPLATES
        .iter()
        .map(|(name, prompt)| ((*name).into(), (*prompt).into()))
        .collect()
}

pub fn find(name: &str) -> Option<&'static str> {
    TEMPLATES
        .iter()
        .find(|(candidate, _)| *candidate == name)
        .map(|(_, prompt)| *prompt)
}
